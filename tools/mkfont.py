# mkfont.py — the menus' face, made from the Spectrum's own.
#
# The 48K ROM's character set (#3D00, ' ' to the copyright sign) with the
# right column of every cell dropped: only '_' and the copyright sign ever
# use it, while the left one stays blank in nearly every glyph and keeps
# the letters apart -- so the glyphs are the ROM's, 7 pixels to a cell,
# 45 to a line of the menu.
# 0x80-0x86 are the menus' own symbols, drawn here to match.
#
#   python3 tools/mkfont.py > src/ui/ui_font.c

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rom = open(os.path.join(ROOT, 'roms', '48.rom'), 'rb').read()
font = rom[0x3D00:0x3D00 + 96 * 8]

# Bit 6 is the leftmost pixel of a 7-pixel cell, as ui_gfx.c reads it;
# column 0 is the gap, as it is in the ROM's glyphs.
SYMBOLS = {
    0x80: ['....#..', '...###.', '..#.#.#', '....#..', '....#..', '....#..', '....#..', '.......'],  # up
    0x81: ['....#..', '....#..', '....#..', '....#..', '..#.#.#', '...###.', '....#..', '.......'],  # down
    0x82: ['.......', '....#..', '.....#.', '.######', '.....#.', '....#..', '.......', '.......'],  # right
    0x83: ['.......', '...#...', '..#....', '.######', '..#....', '...#...', '.......', '.......'],  # left
    0x84: ['.......', '......#', '......#', '...#..#', '..##..#', '.######', '..##...', '...#...'],  # return
    0x85: ['.......', '..#....', '...#...', '....#..', '...#...', '..#....', '.......', '.......'],  # chevron >
    0x86: ['.......', '....#..', '...#...', '..#....', '...#...', '....#..', '.......', '.......'],  # chevron <
}
NAMES = {0x80: 'up', 0x81: 'down', 0x82: 'right', 0x83: 'left', 0x84: 'return',
         0x85: 'chevron >', 0x86: 'chevron <', 0x7F: 'copyright'}

print('''/*
 * frank-dino — an RP2350B acting as the whole machine around a real Z80
 *
 * Copyright (c) 2026 Mikhail Matveev <xtreme@rh1.tech>
 * SPDX-License-Identifier: GPL-3.0-or-later
 *
 * The menus' face: the ZX Spectrum's own character set, from the 48K ROM
 * (Sinclair Research; the ROMs are redistributed with Amstrad's
 * permission, see roms/README.md), narrowed to a 7-pixel cell. 0x80-0x86
 * are the menus' symbols, drawn to match. GENERATED by tools/mkfont.py.
 *
 * One byte per row, eight rows, bit 6 the leftmost pixel.
 */
#include "ui_font.h"

const uint8_t ui_font[UI_FONT_COUNT * UI_FONT_H] = {''')
for c in range(0x20, 0x87):
    if c in SYMBOLS:
        rows = [int(r.replace('.', '0').replace('#', '1'), 2) for r in SYMBOLS[c]]
    else:
        rows = [b >> 1 for b in font[(c - 0x20) * 8:(c - 0x20) * 8 + 8]]
    name = NAMES.get(c, chr(c) if c != 0x5C else 'backslash')
    print('    ' + ','.join(f'0x{r:02X}' for r in rows) + f',  // 0x{c:02X} {name}')
print('};')
