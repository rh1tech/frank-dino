/*
 * Putting a Z80 into a state it did not get to by itself.
 *
 * This is the one thing an emulator gets for free and real hardware does
 * not. Loading a snapshot means restoring twelve registers, two shadow
 * sets, the interrupt mode, the interrupt flip-flop and the program
 * counter — and there is no way to write a register of a Z84C00 from
 * outside it. The CPU has to be persuaded to load them itself.
 *
 * So: build a short program that does it, and put that program where the
 * CPU will fetch it.
 *
 * Every value is an immediate operand, so the whole restore is a few
 * dozen generated bytes and touches no guest RAM at all — which matters,
 * because on a 48K snapshot every byte of RAM belongs to the snapshot and
 * a trampoline written into it would be corrupting the thing it is
 * restoring. The generated code lives in a 16 KB page mapped over the ROM
 * window, which a snapshot never owns.
 *
 * AF and AF' have no "load immediate" form, so they are popped: the
 * values sit in the same page and SP is pointed at them for two
 * instructions before being set to its real value.
 *
 * The last instruction is a jump to the snapshot's PC, after which the
 * page must become the real ROM again. That swap happens on the first
 * opcode fetch after the jump's own, which is the moment the CPU has
 * finished reading the jump and nothing of the trampoline is needed any
 * more.
 */
#pragma once

#include <stdbool.h>
#include <stdint.h>

/*
 * Everything a .SNA or .Z80 carries about the CPU.
 *
 * Laid out as the snapshot formats think of it rather than as the Z80
 * does, so a loader can fill it in without reordering.
 */
typedef struct z80_state_s {
    uint16_t af, bc, de, hl;
    uint16_t af_, bc_, de_, hl_;        // the shadow set
    uint16_t ix, iy, sp, pc;
    uint8_t  i, r;
    uint8_t  im;                        // 0, 1 or 2
    bool     iff;                       // interrupts enabled on entry
    uint8_t  border;                    // 0-7
    uint8_t  port7ffd;                  // paging latch, 128K snapshots
    uint8_t  port1ffd;                  // the +3's and Scorpion's second latch
    uint8_t  portdffd;                  // the Profi's third
} z80_state_t;

/*
 * The trampoline's page, lent out.
 *
 * The register dump in spectrum.c maps a stub over the ROM the same way
 * the trampoline does, and never at the same time -- so it borrows this
 * page rather than keeping sixteen kilobytes of its own.
 */
uint8_t *spec_launch_page(void);

/*
 * Start the machine in that state.
 *
 * RAM must already be loaded. Resets the CPU, runs the generated restore
 * code, and leaves the Z80 executing at st->pc with the real ROM back in
 * the bottom window. Returns false if the CPU never reached the jump,
 * which means something is wrong with the bus rather than the snapshot.
 */
bool spec_launch(const z80_state_t *st);

/*
 * How far the last spec_launch() got, for when it returns false.
 * Zero means the CPU never fetched the first byte of the trampoline.
 */
extern uint32_t spec_launch_opfetches;

/*
 * Prove the trampoline works, without needing anything to load.
 *
 * Puts a short program in RAM that writes seven registers to known
 * addresses, launches it with values chosen so that no two registers
 * could be confused for each other, and checks what arrived. Everything
 * snapshot loading depends on is exercised: both register sets, the
 * index registers, the stack pointer, the jump out of the trampoline
 * page and the swap back to ROM.
 *
 * Runs at boot because it costs a few milliseconds and it is the part of
 * loading a snapshot that fails silently — a snapshot restored with one
 * wrong register does not report anything, it just behaves oddly.
 *
 * Fills `detail` with what went wrong, for the report.
 */
bool spec_launch_selftest(char *detail, unsigned detail_len);
